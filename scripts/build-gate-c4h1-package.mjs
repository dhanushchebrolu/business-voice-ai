#!/usr/bin/env node
// Builds the GATE C4-H1 production package for migration 20261122090000
// (campaign retry limits) from the repository files, so the executed and
// recorded SQL is byte-identical to them:
//   docs/gate-c4h1-execute-20261122090000.sql   apply (guard, migration, history, check)
//   docs/gate-c4h1-rollback-20261122090000.sql  roll back (guard, drop, history, check)
// Usage: node scripts/build-gate-c4h1-package.mjs [--system-id <id>] [--database <name>] [--out <dir>]
// Defaults target production (system identifier 7678069749886157684, database
// "postgres", output docs/). A rehearsal build for another cluster passes its own id.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const SYSTEM_ID = arg("--system-id", "7678069749886157684");
const DATABASE = arg("--database", "postgres");
const OUT = arg("--out", join(root, "docs"));

const VERSION = "20261122090000";
const NAME = "campaign_retry_limits";
const PREVIOUS = "20261121090000";
const MIGRATION_PATH = `supabase/migrations/${VERSION}_${NAME}.sql`;
const ROLLBACK_PATH = `docs/production-rollback-${VERSION}-campaign-retry-limits.sql`;
const read = (p) => readFileSync(join(root, p), "utf8");
const sha256 = (s) => createHash("sha256").update(s, "utf8").digest("hex");
const md5 = (s) => createHash("md5").update(s, "utf8").digest("hex");
const migration = read(MIGRATION_PATH);
const rollback = read(ROLLBACK_PATH);

const TAG = "$gate_c4h1_mig$";
if (migration.includes(TAG)) throw new Error("dollar tag collides with the migration text");
if (/^\s*(BEGIN|COMMIT|ROLLBACK)\s*;/im.test(migration))
  throw new Error("the migration must not control the transaction");
const rollbackSql = rollback
  .split("\n")
  .filter((l) => !/^\s*(BEGIN|COMMIT);\s*$/.test(l))
  .join("\n");

// pg_get_constraintdef of the two constraints, exactly (checked after the migration).
const STATUSES_DEF =
  "CHECK ((retry_statuses <@ ARRAY['no_answer'::text, 'busy'::text, 'failed'::text]))";
const MINUTES_DEF = "CHECK (((retry_after_minutes >= 15) AND (retry_after_minutes <= 10080)))";
const lit = (x) => `'${x.replace(/'/g, "''")}'`;

// Rows the migration must not change (it only adds constraints).
const fp = (table) =>
  `(SELECT '${table}:' || count(*) || ':' || coalesce(md5(string_agg(to_jsonb(x)::text, '|' ORDER BY to_jsonb(x)::text)), '-') FROM public.${table} x)`;
const FINGERPRINT = [
  "campaigns",
  "campaign_contacts",
  "phone_numbers",
  "agent_configs",
  "platform_settings",
]
  .map(fp)
  .join(" || ';' || ");
const CONSTRAINT_COUNT = `(SELECT count(*) FROM pg_constraint WHERE conrelid = 'public.campaigns'::regclass
        AND conname IN ('campaigns_retry_statuses_allowed', 'campaigns_retry_after_minutes_range'))`;

const header = (title) => `-- ${title}
-- Target: Supabase project eorazvlmqwunmhwviocn, database "${DATABASE}",
-- PostgreSQL system identifier ${SYSTEM_ID}.
-- Generated by scripts/build-gate-c4h1-package.mjs from:
--   ${MIGRATION_PATH}  ${sha256(migration)}
--   ${ROLLBACK_PATH}  ${sha256(rollback)}
-- Run ONCE, as ONE request (the query channel runs it as ONE transaction; any
-- error, including every guard and check below, rolls back EVERYTHING):
--   npx -y supabase@2.120.0 db query --linked --project-ref eorazvlmqwunmhwviocn -f <this file>
-- No BEGIN/COMMIT on purpose.

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
`;

const identityGuard = `  IF (SELECT system_identifier::text FROM pg_control_system()) IS DISTINCT FROM '${SYSTEM_ID}' THEN
    RAISE EXCEPTION 'GATE_C4H1_WRONG_DATABASE: system identifier %', (SELECT system_identifier::text FROM pg_control_system());
  END IF;
  IF current_database() IS DISTINCT FROM '${DATABASE}' THEN
    RAISE EXCEPTION 'GATE_C4H1_WRONG_DATABASE: database %', current_database();
  END IF;`;

const execute = `${header(`GATE C4-H1 execution script: migration ${VERSION} (campaign retry limits).`)}
-- ===== Guard: abort before any change unless this is the expected database in the expected state =====
DO $guard$
DECLARE
  outside integer;
BEGIN
${identityGuard}
  IF (SELECT max(version) FROM supabase_migrations.schema_migrations) IS DISTINCT FROM '${PREVIOUS}' THEN
    RAISE EXCEPTION 'GATE_C4H1_UNEXPECTED_HISTORY: latest is %', (SELECT max(version) FROM supabase_migrations.schema_migrations);
  END IF;
  IF ${CONSTRAINT_COUNT} <> 0 THEN
    RAISE EXCEPTION 'GATE_C4H1_OBJECTS_ALREADY_EXIST: a retry constraint already exists';
  END IF;
  -- GATE C1 is in place (this migration builds on its campaign engine).
  IF to_regprocedure('public.admit_campaign_outbound_call(uuid, uuid, uuid, text, integer, integer, timestamptz, text, text)') IS NULL
     OR NOT EXISTS (SELECT 1 FROM public.platform_settings WHERE key = 'outbound.calling_paused') THEN
    RAISE EXCEPTION 'GATE_C4H1_PRECONDITION: the GATE C1 campaign engine is not in place';
  END IF;
  -- Every existing campaign already satisfies the limits (ADD CONSTRAINT would fail anyway; this names the reason).
  SELECT count(*) INTO outside FROM public.campaigns
   WHERE NOT (retry_statuses <@ ARRAY['no_answer', 'busy', 'failed']::text[])
      OR retry_after_minutes NOT BETWEEN 15 AND 10080;
  IF outside <> 0 THEN
    RAISE EXCEPTION 'GATE_C4H1_PRECONDITION: % campaign(s) outside the retry limits; review them first', outside;
  END IF;
  PERFORM set_config('gate_c4h1.data_before', md5(${FINGERPRINT}), true);
END
$guard$;

-- ===== The migration, byte for byte (${MIGRATION_PATH}) =====
${migration}
-- ===== History =====
INSERT INTO supabase_migrations.schema_migrations (version, name, statements)
VALUES ('${VERSION}', '${NAME}', ARRAY[${TAG}${migration}${TAG}]);

-- ===== Check, inside the same transaction: any failure rolls everything back =====
DO $check$
BEGIN
  IF (SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'public.campaigns'::regclass
        AND conname = 'campaigns_retry_statuses_allowed') IS DISTINCT FROM ${lit(STATUSES_DEF)} THEN
    RAISE EXCEPTION 'GATE_C4H1_CHECK: campaigns_retry_statuses_allowed differs';
  END IF;
  IF (SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'public.campaigns'::regclass
        AND conname = 'campaigns_retry_after_minutes_range') IS DISTINCT FROM ${lit(MINUTES_DEF)} THEN
    RAISE EXCEPTION 'GATE_C4H1_CHECK: campaigns_retry_after_minutes_range differs';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.campaigns'::regclass
               AND conname IN ('campaigns_retry_statuses_allowed', 'campaigns_retry_after_minutes_range') AND NOT convalidated) THEN
    RAISE EXCEPTION 'GATE_C4H1_CHECK: a constraint is not validated';
  END IF;
  IF (SELECT md5(statements[1]) FROM supabase_migrations.schema_migrations WHERE version = '${VERSION}') IS DISTINCT FROM '${md5(migration)}' THEN
    RAISE EXCEPTION 'GATE_C4H1_CHECK: recorded migration text differs';
  END IF;
  IF md5(${FINGERPRINT}) IS DISTINCT FROM current_setting('gate_c4h1.data_before', true) THEN
    RAISE EXCEPTION 'GATE_C4H1_CHECK: existing data changed';
  END IF;
END
$check$;

SELECT json_build_object(
  'applied', '${VERSION}',
  'system_identifier', (SELECT system_identifier::text FROM pg_control_system()),
  'database', current_database(),
  'latest_migration', (SELECT max(version) FROM supabase_migrations.schema_migrations),
  'constraints', ${CONSTRAINT_COUNT},
  'existing_data_unchanged', md5(${FINGERPRINT}) = current_setting('gate_c4h1.data_before', true),
  'lock_timeout', current_setting('lock_timeout'),
  'statement_timeout', current_setting('statement_timeout')
) AS gate_c4h1_result;
`;

const rollbackScript = `${header(`GATE C4-H1 rollback script: migration ${VERSION} (campaign retry limits).`)}
-- Removes the two constraints and the history row; no data changes. The
-- application keeps enforcing the same limits (campaign-outcome.ts, launch).
DO $guard$
BEGIN
${identityGuard}
  IF (SELECT max(version) FROM supabase_migrations.schema_migrations) IS DISTINCT FROM '${VERSION}' THEN
    RAISE EXCEPTION 'GATE_C4H1_ROLLBACK_UNEXPECTED_HISTORY: latest is %', (SELECT max(version) FROM supabase_migrations.schema_migrations);
  END IF;
  PERFORM set_config('gate_c4h1.data_before', md5(${FINGERPRINT}), true);
END
$guard$;

-- ===== The reviewed rollback statements (${ROLLBACK_PATH}, without BEGIN/COMMIT) =====
${rollbackSql}
DELETE FROM supabase_migrations.schema_migrations WHERE version = '${VERSION}';

DO $check$
BEGIN
  IF ${CONSTRAINT_COUNT} <> 0 THEN
    RAISE EXCEPTION 'GATE_C4H1_ROLLBACK_CHECK: a retry constraint remains';
  END IF;
  IF (SELECT max(version) FROM supabase_migrations.schema_migrations) IS DISTINCT FROM '${PREVIOUS}' THEN
    RAISE EXCEPTION 'GATE_C4H1_ROLLBACK_CHECK: history is not back to ${PREVIOUS}';
  END IF;
  IF md5(${FINGERPRINT}) IS DISTINCT FROM current_setting('gate_c4h1.data_before', true) THEN
    RAISE EXCEPTION 'GATE_C4H1_ROLLBACK_CHECK: existing data changed';
  END IF;
END
$check$;

SELECT json_build_object(
  'rolled_back', '${VERSION}',
  'latest_migration', (SELECT max(version) FROM supabase_migrations.schema_migrations),
  'constraints', ${CONSTRAINT_COUNT},
  'existing_data_unchanged', md5(${FINGERPRINT}) = current_setting('gate_c4h1.data_before', true)
) AS gate_c4h1_rollback_result;
`;

writeFileSync(join(OUT, `gate-c4h1-execute-${VERSION}.sql`), execute);
writeFileSync(join(OUT, `gate-c4h1-rollback-${VERSION}.sql`), rollbackScript);
console.log(
  JSON.stringify({
    systemId: SYSTEM_ID,
    database: DATABASE,
    migrationSha256: sha256(migration),
    executeSha256: sha256(execute),
    rollbackSha256: sha256(rollbackScript),
  }),
);
