#!/usr/bin/env bash
# Creates services/voice-agent/deploy/local/.env for the LOCAL voice stack
# (deploy/docker-compose.dev.yml) with freshly generated secrets. Never
# overwrites an existing file. Prints no secret values.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
target="$here/.env"

if [ -e "$target" ]; then
  echo "refusing: $target already exists (delete it first to regenerate)" >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

umask 077
{
  echo "# Generated by init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). LOCAL ONLY. Do not commit."
  echo "LIVEKIT_API_KEY=APIlocal$(openssl rand -hex 6)"
  echo "LIVEKIT_API_SECRET=$(openssl rand -hex 32)"
  echo "REDIS_PASSWORD=$(openssl rand -hex 24)"
  echo "VOICE_AGENT_HMAC_SECRET=$(openssl rand -hex 32)"
  echo "# Required: your Sarvam API key (STT, TTS, LLM). Keep a spending limit on it."
  echo "SARVAM_API_KEY="
  # Every optional variable from .env.example, left empty (= compose default).
  grep -E '^[A-Z0-9_]+=$' "$here/.env.example" \
    | grep -vE '^(LIVEKIT_API_KEY|LIVEKIT_API_SECRET|REDIS_PASSWORD|VOICE_AGENT_HMAC_SECRET|SARVAM_API_KEY)='
} > "$target"
chmod 600 "$target"
echo "wrote $target (mode 600). Next: set SARVAM_API_KEY in it."
