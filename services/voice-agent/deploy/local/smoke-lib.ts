/**
 * Safety rails for the LOCAL smoke test (deploy/local/smoke.ts --sip-call),
 * kept free of I/O so tests/local-smoke-guards.spec.ts can prove them.
 *
 * The smoke test creates a SIP inbound trunk and a dispatch rule on the
 * LiveKit server it talks to. On a production or staging server that would
 * re-route real calls, so:
 *
 *   1. Names are per run ("clickai-local-smoke-<runId>-inbound/-dispatch",
 *      rooms "smoke-call-<runId>-…") and can never equal a production name
 *      (clickai-vobiz-inbound, clickai-vobiz-outbound, clickai-receptionist).
 *   2. The target must be demonstrably local, with independent evidence:
 *      a loopback URL, an init-env.sh key id ("APIlocal" + 12 hex), the
 *      server must already have delivered a signed webhook for a room this
 *      run created to this process (a remote server posts to its own
 *      webhook URL, not here), and the server must hold no object with a
 *      production name and no trunk with the run's test number.
 *   3. Cleanup deletes by the ids this run created and recorded, only after
 *      re-reading each object and confirming it still carries this run's
 *      name. It never lists-and-deletes by name.
 */
import { randomBytes } from "node:crypto";
import { RoomAgentDispatch, RoomConfiguration, type SipClient } from "livekit-server-sdk";
import {
  DISPATCH_RULE_NAME,
  INBOUND_TRUNK_NAME,
  OUTBOUND_TRUNK_NAME,
} from "../livekit/sip-provisioning.ts";

/** Production object names: used ONLY to refuse, never to create or delete. */
export const PROTECTED_SIP_NAMES: ReadonlySet<string> = new Set([
  INBOUND_TRUNK_NAME,
  OUTBOUND_TRUNK_NAME,
  DISPATCH_RULE_NAME,
]);
export const SMOKE_NAME_PREFIX = "clickai-local-smoke-";
export const SMOKE_ROOM_PREFIX = "smoke-call-";
const RUN_ID = /^[0-9a-f]{12}$/;
const SMOKE_NAME = /^clickai-local-smoke-[0-9a-f]{12}-(inbound|dispatch)$/;
/** init-env.sh: LIVEKIT_API_KEY=APIlocal$(openssl rand -hex 6). */
export const LOCAL_KEY_PATTERN = /^APIlocal[0-9a-f]{12}$/;
const LOOPBACK = new Set(["127.0.0.1", "localhost", "[::1]", "::1"]);

export class SmokeGuardError extends Error {
  override name = "SmokeGuardError";
}

export type SmokeSipApi = Pick<
  SipClient,
  | "listSipInboundTrunk"
  | "listSipOutboundTrunk"
  | "listSipDispatchRule"
  | "createSipInboundTrunk"
  | "createSipDispatchRule"
  | "deleteSipTrunk"
  | "deleteSipDispatchRule"
>;

export interface SmokeNames {
  runId: string;
  trunk: string;
  rule: string;
  roomPrefix: string;
  /** A per-run number in a fictitious range, so stale runs never collide. */
  number: string;
}

export function newRunId(): string {
  return randomBytes(6).toString("hex");
}

/** Throws unless `name` is a smoke-test name (and not a production one). */
export function assertSmokeName(name: string): void {
  if (PROTECTED_SIP_NAMES.has(name))
    throw new SmokeGuardError(`refusing to touch production SIP object "${name}"`);
  if (!SMOKE_NAME.test(name))
    throw new SmokeGuardError(`"${name}" is not a local smoke-test SIP object name`);
}

export function smokeNames(runId: string): SmokeNames {
  if (!RUN_ID.test(runId)) throw new SmokeGuardError("run id must be 12 hex characters");
  const n: SmokeNames = {
    runId,
    trunk: `${SMOKE_NAME_PREFIX}${runId}-inbound`,
    rule: `${SMOKE_NAME_PREFIX}${runId}-dispatch`,
    roomPrefix: `${SMOKE_ROOM_PREFIX}${runId}-`,
    number: `+9112345${(parseInt(runId.slice(0, 8), 16) % 100_000).toString().padStart(5, "0")}`,
  };
  assertSmokeName(n.trunk);
  assertSmokeName(n.rule);
  return n;
}

/** Static evidence: loopback URL and an init-env.sh key id. */
export function assertLocalTarget(p: { url: string; apiKey: string }): void {
  let u: URL;
  try {
    u = new URL(p.url);
  } catch {
    throw new SmokeGuardError("LiveKit URL is not a valid URL");
  }
  if (!["http:", "ws:"].includes(u.protocol) || !LOOPBACK.has(u.hostname))
    throw new SmokeGuardError(`LiveKit URL must be plain http/ws on loopback, got ${u.host}`);
  if (!LOCAL_KEY_PATTERN.test(p.apiKey))
    throw new SmokeGuardError(
      "LIVEKIT_API_KEY is not a local key generated by deploy/local/init-env.sh (APIlocal + 12 hex)",
    );
}

/**
 * Runtime evidence: the server delivered a verified webhook for `room` (a
 * room this run created) to this process. A remote server reached through a
 * tunnel posts webhooks to its own configured URL, not to the local fake klyro.
 */
export function assertWebhookProof(
  webhooks: ReadonlyArray<{ ok: boolean; room?: string | undefined }>,
  room: string | null,
): void {
  if (!room || !webhooks.some((w) => w.ok && w.room === room))
    throw new SmokeGuardError(
      "no verified webhook for this run's room reached the local fake klyro: the server is not demonstrably local",
    );
}

/** Webhook events still missing for `room` (verified ones only). */
export function missingWebhookEvents(
  webhooks: ReadonlyArray<{ ok: boolean; event: string; room?: string | undefined }>,
  room: string,
  required: readonly string[],
): string[] {
  const seen = new Set(webhooks.filter((w) => w.ok && w.room === room).map((w) => w.event));
  return required.filter((e) => !seen.has(e));
}

/** The single room of this run (unique per-run prefix); ambiguity is an error. */
export function selectRunRoom(roomNames: readonly string[], prefix: string): string | null {
  if (!prefix.startsWith(SMOKE_ROOM_PREFIX) || prefix.length <= SMOKE_ROOM_PREFIX.length)
    throw new SmokeGuardError("room prefix must be a per-run smoke prefix");
  const mine = roomNames.filter((n) => n.startsWith(prefix));
  if (mine.length > 1) throw new SmokeGuardError(`${mine.length} rooms match ${prefix}`);
  return mine[0] ?? null;
}

/**
 * Refuses a server holding production objects or a trunk with this run's
 * number. Returns the names of stale smoke objects from earlier runs (left
 * alone: this run deletes only what it created).
 */
export async function preflight(sip: SmokeSipApi, names: SmokeNames): Promise<string[]> {
  const [inbound, outbound, rules] = await Promise.all([
    sip.listSipInboundTrunk(),
    sip.listSipOutboundTrunk(),
    sip.listSipDispatchRule(),
  ]);
  const all = [...inbound, ...outbound, ...rules].map((o) => o.name);
  const prod = all.filter((n) => PROTECTED_SIP_NAMES.has(n));
  if (prod.length)
    throw new SmokeGuardError(
      `server holds production SIP objects (${[...new Set(prod)].join(", ")}): refusing to run the SIP smoke test against it`,
    );
  if (inbound.some((t) => (t.numbers ?? []).includes(names.number)))
    throw new SmokeGuardError(`an existing trunk already claims ${names.number}`);
  if (all.some((n) => n === names.trunk || n === names.rule))
    throw new SmokeGuardError("objects with this run's names already exist");
  return all.filter((n) => n.startsWith(SMOKE_NAME_PREFIX));
}

export interface CleanupResult {
  deleted: string[];
  skipped: string[];
  failed: string[];
}

/** Creates this run's trunk + rule and remembers exactly what it created. */
export class SmokeSipRun {
  readonly names: SmokeNames;
  private readonly sip: SmokeSipApi;
  private trunkId: string | null = null;
  private ruleId: string | null = null;

  constructor(sip: SmokeSipApi, names: SmokeNames) {
    assertSmokeName(names.trunk);
    assertSmokeName(names.rule);
    this.sip = sip;
    this.names = names;
  }

  get created(): { trunkId: string | null; ruleId: string | null } {
    return { trunkId: this.trunkId, ruleId: this.ruleId };
  }

  async setup(p: { allowedAddresses: string[]; agentName: string }): Promise<void> {
    const t = await this.sip.createSipInboundTrunk(this.names.trunk, [this.names.number], {
      allowedAddresses: p.allowedAddresses,
    });
    this.trunkId = t.sipTrunkId;
    if (t.name !== this.names.trunk)
      throw new SmokeGuardError(`created trunk came back as "${t.name}"`);
    const r = await this.sip.createSipDispatchRule(
      { type: "individual", roomPrefix: this.names.roomPrefix },
      {
        name: this.names.rule,
        trunkIds: [t.sipTrunkId],
        roomConfig: new RoomConfiguration({
          agents: [new RoomAgentDispatch({ agentName: p.agentName })],
        }),
      },
    );
    this.ruleId = r.sipDispatchRuleId;
    if (r.name !== this.names.rule)
      throw new SmokeGuardError(`created dispatch rule came back as "${r.name}"`);
  }

  /**
   * Deletes only the ids recorded by setup(), each after re-reading it and
   * confirming it still has this run's name. Never throws; reports instead.
   */
  async cleanup(): Promise<CleanupResult> {
    const out: CleanupResult = { deleted: [], skipped: [], failed: [] };
    const del = async (
      kind: string,
      id: string | null,
      expected: string,
      list: () => Promise<Array<{ name: string; id: string }>>,
      remove: (id: string) => Promise<unknown>,
    ) => {
      if (!id) return;
      try {
        const current = (await list()).find((o) => o.id === id);
        if (!current) return void out.skipped.push(`${kind} ${id}: already gone`);
        if (current.name !== expected || PROTECTED_SIP_NAMES.has(current.name))
          return void out.skipped.push(`${kind} ${id}: name is "${current.name}", not ours`);
        assertSmokeName(current.name);
        await remove(id);
        out.deleted.push(`${kind} ${expected}`);
      } catch (e) {
        out.failed.push(`${kind} ${id}: ${(e as Error).message}`);
      }
    };
    // Rule first: it references the trunk.
    await del(
      "dispatch rule",
      this.ruleId,
      this.names.rule,
      async () =>
        (await this.sip.listSipDispatchRule()).map((r) => ({
          name: r.name,
          id: r.sipDispatchRuleId,
        })),
      (id) => this.sip.deleteSipDispatchRule(id),
    );
    await del(
      "inbound trunk",
      this.trunkId,
      this.names.trunk,
      async () =>
        (await this.sip.listSipInboundTrunk()).map((t) => ({ name: t.name, id: t.sipTrunkId })),
      (id) => this.sip.deleteSipTrunk(id),
    );
    return out;
  }
}
