/**
 * Issues an invitation. Only hashes are stored — the raw link and PIN are
 * returned exactly once to the admin and can never be read back.
 */
export const createInvitation = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string; email: string; expiresInHours?: number; withPin?: boolean }) => {
    if (!input?.orgId) throw new Error("orgId is required");
    if (!input.email?.includes("@")) throw new Error("A valid email is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const email = data.email.trim().toLowerCase();
    const token = await randomToken();
    const pin = data.withPin ? await randomPin() : null;
    const hours = Math.min(Math.max(data.expiresInHours ?? 72, 1), 720);

    // Supersede any outstanding invitation for this org.
    await supabaseAdmin
      .from("organization_invitations")
      .update({ revoked_at: new Date().toISOString() })
      .eq("organization_id", data.orgId)
      .is("accepted_at", null)
      .is("revoked_at", null);

    const { data: row, error } = await supabaseAdmin
      .from("organization_invitations")
      .insert({
        organization_id: data.orgId,
        email,
        token_hash: await sha256(token),
        pin_hash: pin ? await sha256(pin) : null,
        expires_at: new Date(Date.now() + hours * 3_600_000).toISOString(),
        created_by: admin.userId,
      })
      .select("id, expires_at")
      .single();
    if (error) throw error;

    await recordEvent(data.orgId, "access", "Invitation generated", `Sent to ${email}`, admin.email);
    await writeAudit(admin, {
      action: "CREATE_INVITATION",
      entityType: "invitation",
      entityId: row.id,
      organizationId: data.orgId,
      newValue: { email, expires_at: row.expires_at, pin: Boolean(pin) },
      reason: "Customer access invitation issued",
    });

    // Raw secrets are returned once, never persisted in readable form.
    return { id: row.id, token, pin, email, expiresAt: row.expires_at };
  });

