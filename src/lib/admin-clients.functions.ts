/**
 * Read-only customer workspace snapshot for an active support session. The
 * admin never gains the customer's credentials and cannot write through this
 * path — every field is fetched server-side after re-verifying the session.
 */
export const getSupportSessionView = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { sessionId: string; token: string }) => {
    if (!input?.sessionId || !input.token) throw new Error("A valid support session is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.read");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const { data: sess } = await supabaseAdmin
      .from("admin_support_sessions")
      .select("*")
      .eq("id", data.sessionId)
      .maybeSingle();
    if (!sess || sess.admin_user_id !== admin.userId) throw new Error("Support session not found");
    if (sess.ended_at) throw new Error("This support session has ended");
    if (new Date(sess.expires_at) < new Date()) throw new Error("This support session has expired");
    if ((await sha256(data.token)) !== sess.token_hash) throw new Error("Invalid support session token");

    const orgId = sess.organization_id;
    const [org, business, numbers, calls, leads, wallet, agent] = await Promise.all([
      supabaseAdmin.from("organizations").select("*").eq("id", orgId).maybeSingle(),
      supabaseAdmin.from("businesses").select("*").eq("organization_id", orgId).maybeSingle(),
      supabaseAdmin.from("phone_numbers").select("*").eq("organization_id", orgId),
      supabaseAdmin
        .from("call_logs")
        .select("id, direction, status, duration_seconds, started_at, summary")
        .eq("organization_id", orgId)
        .order("started_at", { ascending: false })
        .limit(20),
      supabaseAdmin
        .from("leads")
        .select("id, name, phone, status, score, created_at")
        .eq("organization_id", orgId)
        .order("created_at", { ascending: false })
        .limit(20),
      supabaseAdmin.from("wallet_transactions").select("amount").eq("organization_id", orgId),
      supabaseAdmin.from("agent_configs").select("*").eq("organization_id", orgId).maybeSingle(),
    ]);

    return {
      session: { id: sess.id, expiresAt: sess.expires_at, adminEmail: sess.admin_email },
      organization: org.data,
      business: business.data,
      numbers: numbers.data ?? [],
      calls: calls.data ?? [],
      leads: leads.data ?? [],
      walletBalance: (wallet.data ?? []).reduce((s, t) => s + t.amount, 0),
      agent: agent.data,
    };
  });

