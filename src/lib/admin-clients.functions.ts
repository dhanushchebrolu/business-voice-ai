/**
 * Creates a customer record from the admin control centre.
 *
 * The organization is created in `not_provisioned` so nothing unlocks until an
 * admin explicitly provisions it. `client_id` is generated by the database and
 * is immutable. No auth user is created here — the customer joins through a
 * hashed invitation.
 */
export const createClientAccount = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: CreateClientInput) => {
    if (!input?.businessName?.trim()) throw new Error("Business name is required");
    if (!input.email?.includes("@")) throw new Error("A valid email is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const email = data.email.trim().toLowerCase();

    const { data: clash } = await supabaseAdmin
      .from("organizations")
      .select("id, client_id, name")
      .ilike("contact_email", email)
      .maybeSingle();
    if (clash) throw new Error(`${clash.client_id} (${clash.name}) already uses that email`);

    const { data: org, error } = await supabaseAdmin
      .from("organizations")
      .insert({
        name: data.businessName.trim(),
        owner_id: admin.userId, // placeholder; transferred when the customer accepts the invitation
        created_by_admin: admin.userId,
        country: data.country ?? "IN",
        account_status: "payment_required",
        lifecycle_status: "not_provisioned",
        crm_stage: "lead",
        contact_name: data.fullName?.trim() || null,
        contact_email: email,
        contact_phone: data.phone?.trim() || null,
        city: data.city?.trim() || null,
        address: data.address?.trim() || null,
        website: data.website?.trim() || null,
        industry: data.industry?.trim() || null,
        business_type: data.businessType?.trim() || null,
        gst_number: data.gstNumber?.trim() || null,
        pan_number: data.panNumber?.trim() || null,
        internal_notes: data.internalNotes?.trim() || null,
      })
      .select("id, client_id, name")
      .single();
    if (error) throw error;

    await supabaseAdmin
      .from("subscriptions")
      .insert({ organization_id: org.id, plan: data.plan ?? "starter", status: "expired" });

    const overrides = [
      { key: "setup_fee", customer_amount: data.setupFee },
      { key: "monthly_plan", customer_amount: data.monthlyFee },
      { key: "phone_number", customer_amount: data.numberFee },
    ].filter((o) => typeof o.customer_amount === "number" && Number.isFinite(o.customer_amount));
    if (overrides.length) {
      await supabaseAdmin.from("organization_pricing_overrides").insert(
        overrides.map((o) => ({
          organization_id: org.id,
          key: o.key,
          customer_amount: Math.round(o.customer_amount as number),
          updated_by: admin.userId,
        })),
      );
    }

    if (data.walletOpeningBalance && data.walletOpeningBalance !== 0) {
      await supabaseAdmin.from("wallet_transactions").insert({
        organization_id: org.id,
        amount: Math.round(data.walletOpeningBalance),
        kind: "opening_balance",
        description: "Opening balance set at client creation",
        created_by: admin.userId,
      });
    }

    if (data.notes?.trim()) {
      await supabaseAdmin.from("crm_notes").insert({
        organization_id: org.id,
        admin_user_id: admin.userId,
        admin_email: admin.email,
        body: data.notes.trim(),
      });
    }

    await recordEvent(org.id, "lifecycle", "Client created", `Created by ${admin.email ?? "admin"}`, admin.email);
    await writeAudit(admin, {
      action: "CREATE_CLIENT",
      entityType: "organization",
      entityId: org.id,
      organizationId: org.id,
      newValue: { client_id: org.client_id, name: org.name, email },
      reason: "Client created from admin control centre",
    });

    return { id: org.id, clientId: org.client_id };
  });

/** Updates CRM / profile fields on a client. Client ID can never change. */
export const updateClientProfile = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string; patch: Record<string, string | null> }) => {
    if (!input?.orgId) throw new Error("orgId is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const allowed = [
      "name",
      "contact_name",
      "contact_email",
      "contact_phone",
      "city",
      "address",
      "website",
      "industry",
      "business_type",
      "gst_number",
      "pan_number",
      "internal_notes",
      "crm_stage",
      "follow_up_at",
      "last_contacted_at",
    ];
    const patch: Record<string, string | null> = {};
    for (const [k, v] of Object.entries(data.patch)) if (allowed.includes(k)) patch[k] = v === "" ? null : v;
    if (!Object.keys(patch).length) throw new Error("Nothing to update");

    const { data: before } = await supabaseAdmin.from("organizations").select("*").eq("id", data.orgId).maybeSingle();
    const { error } = await supabaseAdmin.from("organizations").update(patch as never).eq("id", data.orgId);
    if (error) throw error;

    await writeAudit(admin, {
      action: "UPDATE_CLIENT",
      entityType: "organization",
      entityId: data.orgId,
      organizationId: data.orgId,
      oldValue: before ? Object.fromEntries(Object.keys(patch).map((k) => [k, (before as never)[k]])) : null,
      newValue: patch,
      reason: "Client profile updated",
    });
    return { ok: true as const };
  });

/** Moves a client through the lifecycle and keeps account status in step. */
export const setClientLifecycle = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string; status: LifecycleStatus; reason: string }) => {
    if (!input?.orgId || !LIFECYCLE_VALUES.includes(input.status)) throw new Error("Invalid lifecycle status");
    if (!input.reason?.trim()) throw new Error("A reason is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const { data: before } = await supabaseAdmin
      .from("organizations")
      .select("lifecycle_status, account_status")
      .eq("id", data.orgId)
      .maybeSingle();

    const patch: Record<string, unknown> = {
      lifecycle_status: data.status,
      account_status: ACCOUNT_FOR_LIFECYCLE[data.status] ?? "payment_required",
    };
    if (data.status === "provisioning") patch["provisioned_at"] = new Date().toISOString();
    if (data.status === "active") {
      patch["activated_at"] = new Date().toISOString();
      patch["crm_stage"] = "customer";
    }
    if (data.status === "archived") patch["archived_at"] = new Date().toISOString();

    const { error } = await supabaseAdmin.from("organizations").update(patch as never).eq("id", data.orgId);
    if (error) throw error;

    await recordEvent(data.orgId, "lifecycle", `Lifecycle → ${data.status}`, data.reason, admin.email);
    await writeAudit(admin, {
      action: `LIFECYCLE_${data.status.toUpperCase()}`,
      entityType: "organization",
      entityId: data.orgId,
      organizationId: data.orgId,
      oldValue: before,
      newValue: patch,
      reason: data.reason,
    });
    return { ok: true as const };
  });

/**
 * Soft-deletes (archives) a client. Financial and operational history is never
 * removed: payments, wallet ledger, invoices, calls, usage and audit rows stay.
 */
export const archiveClient = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string; confirmation: string; reason: string }) => {
    if (!input?.orgId) throw new Error("orgId is required");
    if (!input.confirmation?.trim()) throw new Error("Type the Client ID to confirm");
    if (!input.reason?.trim()) throw new Error("A reason is required");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const { data: org } = await supabaseAdmin
      .from("organizations")
      .select("client_id, name, lifecycle_status")
      .eq("id", data.orgId)
      .maybeSingle();
    if (!org) throw new Error("Client not found");

    const typed = data.confirmation.trim().toLowerCase();
    if (typed !== org.client_id.toLowerCase() && typed !== org.name.toLowerCase()) {
      throw new Error("Confirmation does not match the Client ID or business name");
    }

    const { error } = await supabaseAdmin
      .from("organizations")
      .update({
        lifecycle_status: "archived",
        account_status: "cancelled",
        archived_at: new Date().toISOString(),
      })
      .eq("id", data.orgId);
    if (error) throw error;

    await supabaseAdmin
      .from("organization_invitations")
      .update({ revoked_at: new Date().toISOString() })
      .eq("organization_id", data.orgId)
      .is("accepted_at", null);

    await recordEvent(data.orgId, "lifecycle", "Client archived", data.reason, admin.email);
    await writeAudit(admin, {
      action: "ARCHIVE_CLIENT",
      entityType: "organization",
      entityId: data.orgId,
      organizationId: data.orgId,
      oldValue: org,
      newValue: { lifecycle_status: "archived" },
      reason: data.reason,
    });
    return { ok: true as const };
  });

