export const listCrm = createServerFn({ method: "GET" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string }) => input)
  .handler(async ({ data, context }) => {
    await assertPlatformAdmin(context.supabase, context.userId, "customers.read");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const [notes, events] = await Promise.all([
      supabaseAdmin
        .from("crm_notes")
        .select("*")
        .eq("organization_id", data.orgId)
        .order("created_at", { ascending: false }),
      supabaseAdmin
        .from("customer_events")
        .select("*")
        .eq("organization_id", data.orgId)
        .order("created_at", { ascending: false })
        .limit(100),
    ]);
    return { notes: notes.data ?? [], events: events.data ?? [] };
  });

export const addCrmNote = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: { orgId: string; body: string; followUpAt?: string | null }) => {
    if (!input?.orgId) throw new Error("orgId is required");
    if (!input.body?.trim()) throw new Error("Note cannot be empty");
    return input;
  })
  .handler(async ({ data, context }) => {
    const admin: PlatformAdmin = await assertPlatformAdmin(context.supabase, context.userId, "customers.write");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const { error } = await supabaseAdmin.from("crm_notes").insert({
      organization_id: data.orgId,
      admin_user_id: admin.userId,
      admin_email: admin.email,
      body: data.body.trim(),
      follow_up_at: data.followUpAt ?? null,
    });
    if (error) throw error;
    if (data.followUpAt) {
      await supabaseAdmin.from("organizations").update({ follow_up_at: data.followUpAt }).eq("id", data.orgId);
    }
    await supabaseAdmin
      .from("organizations")
      .update({ last_contacted_at: new Date().toISOString() })
      .eq("id", data.orgId);
    return { ok: true as const };
  });
