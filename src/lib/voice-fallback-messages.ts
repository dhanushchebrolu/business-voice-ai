export type FallbackMessageKey = BaseMessageKey | CallFlowMessageKey;

/** Every fixed line, in every supported language. */
export const FALLBACK_MESSAGES = Object.fromEntries(
  (Object.keys(BASE_MESSAGES) as VoiceLanguageCode[]).map((code) => [
    code,
    { ...BASE_MESSAGES[code], ...CALL_FLOW_MESSAGES[code] },
  ]),
) as Record<VoiceLanguageCode, Record<FallbackMessageKey, (businessName: string) => string>>;

/**
 * The fixed line `key` in `language` — English when the language isn't a
 * supported one (resolvePrimaryLanguage's own fallback).
 */
export function localizedFallback(
  key: FallbackMessageKey,
  language: string,
  businessName = "",
): string {
  return FALLBACK_MESSAGES[resolvePrimaryLanguage(language)][key](businessName);
}
