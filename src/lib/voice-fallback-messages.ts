/**
 * Fixed lines the runtime speaks without the LLM — when the caller has gone
 * quiet, when the model or STT has failed, or when the call is ending — in
 * every supported voice language.
 *
 * These can't be phrased by the model on demand: most of them are spoken
 * precisely BECAUSE the model is unavailable, and the rest end the call, so
 * an extra model round trip there only adds dead air. Before this table they
 * were English only, so a Tamil call that hit an LLM error heard English
 * read out by a ta-IN voice.
 *
 * English entries are the runtime's existing lines, unchanged. The others
 * are short, plain and polite, and avoid first-person gendered verb forms
 * (Hindi/Marathi/Punjabi), since the agent's voice may be male or female.
 * They should still be reviewed by a native speaker of each language before
 * being relied on.
 */
